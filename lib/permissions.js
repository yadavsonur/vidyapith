export const ROLES = Object.freeze({
  STUDENT: "STUDENT",
  TEACHER: "TEACHER",
  ADMIN: "ADMIN",
});

export const COURSE_ROLES = Object.freeze({
  OWNER: "OWNER",
  EDITOR: "EDITOR",
  INSTRUCTOR: "INSTRUCTOR",
});

export const COURSE_PERMISSIONS = Object.freeze({
  VIEW_TEACHER_COURSE: "VIEW_TEACHER_COURSE",
  EDIT_COURSE: "EDIT_COURSE",
  MANAGE_CONTENT: "MANAGE_CONTENT",
  PUBLISH_COURSE: "PUBLISH_COURSE",
  MANAGE_INSTRUCTORS: "MANAGE_INSTRUCTORS",
  DELETE_COURSE: "DELETE_COURSE",
  MANAGE_ANNOUNCEMENTS: "MANAGE_ANNOUNCEMENTS",
  VIEW_ANALYTICS: "VIEW_ANALYTICS",
});

export const COURSE_ROLE_PERMISSIONS = Object.freeze({
  OWNER: new Set([
    COURSE_PERMISSIONS.VIEW_TEACHER_COURSE,
    COURSE_PERMISSIONS.EDIT_COURSE,
    COURSE_PERMISSIONS.MANAGE_CONTENT,
    COURSE_PERMISSIONS.PUBLISH_COURSE,
    COURSE_PERMISSIONS.MANAGE_INSTRUCTORS,
    COURSE_PERMISSIONS.DELETE_COURSE,
    COURSE_PERMISSIONS.MANAGE_ANNOUNCEMENTS,
    COURSE_PERMISSIONS.VIEW_ANALYTICS,
  ]),
  EDITOR: new Set([
    COURSE_PERMISSIONS.VIEW_TEACHER_COURSE,
    COURSE_PERMISSIONS.EDIT_COURSE,
    COURSE_PERMISSIONS.MANAGE_CONTENT,
    COURSE_PERMISSIONS.PUBLISH_COURSE,
    COURSE_PERMISSIONS.MANAGE_ANNOUNCEMENTS,
    COURSE_PERMISSIONS.VIEW_ANALYTICS,
  ]),
  INSTRUCTOR: new Set([
    COURSE_PERMISSIONS.VIEW_TEACHER_COURSE,
    COURSE_PERMISSIONS.MANAGE_CONTENT,
    COURSE_PERMISSIONS.MANAGE_ANNOUNCEMENTS,
    COURSE_PERMISSIONS.VIEW_ANALYTICS,
  ]),
});

export const isStaffRole = (role) =>
  role === ROLES.TEACHER || role === ROLES.ADMIN;

export const hasCoursePermission = (role, permission) => {
  const permissions = COURSE_ROLE_PERMISSIONS[role];
  return !!permissions?.has(permission);
};
